"""Mode-set construction utilities for permutation shells and cascade seeds."""
from __future__ import annotations

from itertools import permutations
from typing import Dict, Iterable, Tuple

import numpy as np

from .ns_symbol import Array, Mode, ns_bilinear, real_vec


def perm_shell(triple: Tuple[int, int, int]) -> list[Mode]:
    """Unique permutations of an integer triple."""
    return sorted(set(tuple(p) for p in permutations(triple)))


def add_modes(p: Mode, q: Mode) -> Mode:
    return (p[0] + q[0], p[1] + q[1], p[2] + q[2])


def sub_modes(p: Mode, q: Mode) -> Mode:
    return (p[0] - q[0], p[1] - q[1], p[2] - q[2])


def canonical(v: Iterable[int]) -> Mode:
    return tuple(int(x) for x in v)  # type: ignore[return-value]


def level0_amplitudes() -> Dict[Mode, Array]:
    """Symmetric seed: e_i has amplitude s - e_i."""
    return {
        (1, 0, 0): real_vec((0, 1, 1)),
        (0, 1, 0): real_vec((1, 0, 1)),
        (0, 0, 1): real_vec((1, 1, 0)),
    }


def f1_amplitudes() -> Dict[Mode, Array]:
    """First clean shell generated by level0 self interactions."""
    return {
        (1, 1, 0): real_vec((0, 0, 2)),
        (1, 0, 1): real_vec((0, 2, 0)),
        (0, 1, 1): real_vec((2, 0, 0)),
    }


def d_amplitudes() -> Dict[Mode, Array]:
    """Clean desired D = P(2,1,1), induced by F1 x F1.

    Formula: mode with coordinate 2 at i gets (8/3)(s - 2e_i).
    """
    return {
        (2, 1, 1): (8.0 / 3.0) * real_vec((-1, 1, 1)),
        (1, 2, 1): (8.0 / 3.0) * real_vec((1, -1, 1)),
        (1, 1, 2): (8.0 / 3.0) * real_vec((1, 1, -1)),
    }


def l_amplitudes_from_f0_f1() -> Dict[Mode, Array]:
    """First leakage shell L = P(2,1,0) from F0 x F1 with symmetric seed.

    We compute it directly and aggregate by output mode.  Signs/magnitudes follow
    from the chosen real seed amplitudes.
    """
    f0 = level0_amplitudes()
    f1 = f1_amplitudes()
    out: Dict[Mode, Array] = {}
    for p, a in f0.items():
        for q, b in f1.items():
            m = add_modes(p, q)
            # keep P(2,1,0), exclude same-index diagonal s=(1,1,1)
            if sorted(m) == [0, 1, 2]:
                v = ns_bilinear(p, a, q, b)
                out[m] = out.get(m, np.zeros(3, dtype=np.complex128)) + v
    return out


def first_fan_amplitudes() -> Dict[str, Dict[Mode, Array]]:
    return {
        "F0": level0_amplitudes(),
        "F1": f1_amplitudes(),
        "D": d_amplitudes(),
        "L": l_amplitudes_from_f0_f1(),
    }
